interface EmojiPickerProps {
  onSelect: (emoji: string) => void;
  onClose: () => void;
}

export function EmojiPicker({ onSelect, onClose }: EmojiPickerProps) {
  const [activeTab, setActiveTab] = useState(0);

  return (
    <div className="absolute bottom-full mb-2 left-0 z-50 bg-white rounded-2xl shadow-2xl border border-zinc-200 w-72 overflow-hidden animate-in fade-in slide-in-from-bottom-2 duration-200">
      {/* Header tabs */}
      <div className="flex border-b border-zinc-100 bg-zinc-50 overflow-x-auto">
        {EMOJI_CATEGORIES.map((cat, i) => (
          <button
            key={i}
            onClick={() => setActiveTab(i)}
            className={`flex-shrink-0 px-3 py-2 text-[11px] font-semibold transition-colors whitespace-nowrap ${
              activeTab === i
                ? 'text-pink-600 border-b-2 border-pink-500 bg-white'
                : 'text-zinc-500 hover:text-zinc-700'
            }`}
          >
            {cat.label}
          </button>
        ))}
      </div>

      {/* Emoji Grid */}
      <div className="p-3 grid grid-cols-8 gap-0.5 max-h-48 overflow-y-auto">
        {EMOJI_CATEGORIES[activeTab].emojis.map((emoji) => (
          <button
            key={emoji}
            onClick={() => { onSelect(emoji); onClose(); }}
            className="text-xl w-8 h-8 flex items-center justify-center rounded-lg hover:bg-pink-50 transition-colors hover:scale-125 transform duration-100"
            title={emoji}
          >
            {emoji}
          </button>
        ))}
      </div>
    </div>
  );
}
